/**
 * build_report_docx.js
 * Person 2 — Backend Logic, Rules & LLM Integration
 *
 * Combines the monthly report's narrative text + chart image into a single
 * polished .docx file. Run this AFTER generate_monthly_report() has already
 * produced the narrative + chart PNG.
 *
 * Usage (from backend/ folder):
 *   node data/reports/build_report_docx.js "<narrative text>" "<year>" "<month_name>" "<chart_png_path>" "<output_docx_path>"
 *
 * Easiest: call it via the Python helper build_report.py in this same
 * folder, which fetches the narrative from the DB automatically.
 */

const fs = require("fs");
const {
  Document, Packer, Paragraph, TextRun, HeadingLevel,
  ImageRun, AlignmentType, BorderStyle,
} = require("docx");

const [, , narrative, year, monthName, chartPath, outPath] = process.argv;

const chartBuffer = fs.existsSync(chartPath) ? fs.readFileSync(chartPath) : null;

const children = [
  new Paragraph({
    text: "Smart Gym Monitoring System",
    heading: HeadingLevel.TITLE,
  }),
  new Paragraph({
    children: [
      new TextRun({
        text: `Monthly Report — ${monthName} ${year}`,
        bold: true,
        size: 28,
        color: "444444",
      }),
    ],
    spacing: { after: 300 },
  }),
  new Paragraph({
    border: {
      bottom: { style: BorderStyle.SINGLE, size: 6, color: "CCCCCC" },
    },
    spacing: { after: 300 },
  }),
  new Paragraph({
    text: "Summary",
    heading: HeadingLevel.HEADING_1,
  }),
  new Paragraph({
    children: [new TextRun({ text: narrative, size: 24 })],
    spacing: { after: 400 },
  }),
];

if (chartBuffer) {
  children.push(
    new Paragraph({
      text: "Occupancy Trend",
      heading: HeadingLevel.HEADING_1,
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new ImageRun({
          data: chartBuffer,
          type: "png",
          transformation: { width: 550, height: 245 },
        }),
      ],
    })
  );
}

children.push(
  new Paragraph({
    spacing: { before: 600 },
    border: {
      top: { style: BorderStyle.SINGLE, size: 6, color: "CCCCCC" },
    },
  }),
  new Paragraph({
    children: [
      new TextRun({
        text: "Automatically generated by the Smart Gym Monitoring System.",
        italics: true,
        size: 18,
        color: "888888",
      }),
    ],
  })
);

const doc = new Document({
  sections: [
    {
      properties: {
        page: { size: { width: 12240, height: 15840 } }, // US Letter
      },
      children,
    },
  ],
});

Packer.toBuffer(doc).then((buffer) => {
  fs.writeFileSync(outPath, buffer);
  console.log("Report written to:", outPath);
});
